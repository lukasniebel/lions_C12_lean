#!/usr/bin/env python3
"""Generate `LionsC12/AxiomAudit.lean`: one `#print axioms` command for every theorem of the library.

The theorems are enumerated by Lean itself: a temporary (non-module) file importing `LionsC12`
walks the environment and prints every theorem declared in a `LionsC12.*` module whose name is in
the `LionsC12` namespace, skipping private names, internal details, instances and the
automatically generated `congr_simp` lemmas.  The audit module lists them grouped by module, in
the order of the module names.  Run after a successful `scripts/lake build LionsC12`, then run
`scripts/regenerate-audited-declarations.sh` and commit the three files together.

Usage: generate-axiom-audit.py [--check]   (from anywhere; paths are relative to the repository root)

With `--check` nothing is written: the script exits with status 1, printing the theorems that are
missing from or extra in the committed audit module, unless that module is exactly the one this
script would generate.  The release gate runs it in this mode after building the library, so the
inventory of audited theorems is compared with a fresh enumeration of the built environment.
"""
import collections
import difflib
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEAN = ROOT / "scripts" / "lean"
OUT = ROOT / "LionsC12" / "AxiomAudit.lean"

ENUMERATE = r"""
import LionsC12
open Lean Elab Command

run_cmd do
  let env ← getEnv
  for (n, ci) in env.constants.toList do
    let some idx := env.getModuleIdxFor? n | continue
    let mod := env.header.moduleNames[idx.toNat]!
    unless (`LionsC12).isPrefixOf mod do continue
    unless (`LionsC12).isPrefixOf n do continue
    if n.isInternalDetail || isPrivateName n then continue
    if n.getString! == "congr_simp" then continue
    if (← liftCoreM (Lean.Meta.isInstance n)) then continue
    if let .thmInfo _ := ci then
      IO.println s!"{mod} {n}"
"""

HEADER = """module

public import LionsC12

/-!
# Axiom audit

The release trust surface: one `#print axioms` command for every theorem of the library — every
theorem declared in a `LionsC12.*` module, in the `LionsC12` namespace, except private
declarations, instances and automatically generated lemmas.  `LionsC12` (the root module) imports
every module of the development, so this file needs no other import.

`scripts/audit.sh` elaborates this module and pipes the report through
`scripts/check-axiom-audit.awk`, which fails the release gate unless

* every dependency is one of `propext`, `Classical.choice`, `Quot.sound`, and
* the *set* of reported declarations is exactly the checked-in list in
  `scripts/audited-declarations.txt`.

This file is generated by `scripts/generate-axiom-audit.py`; regenerate it, and then the list with
`scripts/regenerate-audited-declarations.sh`, whenever a theorem is added, renamed or removed.
The commands are grouped by module, in the order of the module names.
-/
"""


def main(argv) -> int:
    check = argv[1:] == ["--check"]
    if argv[1:] not in ([], ["--check"]):
        sys.stderr.write(__doc__)
        return 2
    with tempfile.TemporaryDirectory() as tmp:
        script = pathlib.Path(tmp) / "EnumerateTheorems.lean"
        script.write_text(ENUMERATE, encoding="utf-8")
        result = subprocess.run([str(LEAN), str(script)], cwd=ROOT, capture_output=True,
                                text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        return 1
    by_module = collections.defaultdict(set)
    for line in result.stdout.splitlines():
        parts = line.split()
        if len(parts) != 2:
            sys.stderr.write(f"unexpected output line: {line!r}\n")
            return 1
        by_module[parts[0]].add(parts[1])
    lines = [HEADER]
    total = 0
    for module in sorted(by_module):
        lines.append(f"\n-- {module}\n")
        for name in sorted(by_module[module]):
            lines.append(f"#print axioms {name}\n")
            total += 1
    text = "".join(lines)
    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current == text:
            print(f"{OUT.relative_to(ROOT)} lists all {total} theorems of the library")
            return 0
        diff = difflib.unified_diff(current.splitlines(), text.splitlines(), "committed",
                                    "fresh enumeration", lineterm="", n=0)
        sys.stderr.write("\n".join(line for line in diff if line[:1] in "+-") + "\n")
        sys.stderr.write(f"{OUT.relative_to(ROOT)} is out of date: run scripts/generate-axiom-audit.py "
                         "and scripts/regenerate-audited-declarations.sh\n")
        return 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {total} theorems in {len(by_module)} modules")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
